def flex_svg(name):
    raw = (FIG / name).read_text(encoding="utf-8")
    raw = re.sub(r'(<svg\b[^>]*?)\swidth="[^"]*"', r"\1", raw, count=1)
    raw = re.sub(r'(<svg\b[^>]*?)\sheight="[^"]*"', r"\1", raw, count=1)
    raw = re.sub(r"(<svg\b[^>]*>)", r"\1" + SVG_STYLE, raw, count=1)
    return raw


def rows(pairs):
    return "".join(f"<tr><th>{esc(k)}</th><td>{esc(v)}</td></tr>" for k, v in pairs)


