def table(rows):
    head = "".join(f"<th>{esc(h)}</th>" for h in HEAD)
    body = []
    for row in rows:
        body.append("<tr>" + "".join(f"<td>{esc(c)}</td>" for c in row) + "</tr>")
    return f"<table class=\"models\"><thead><tr>{head}</tr></thead><tbody>{''.join(body)}</tbody></table>"


def credit(meta, key):
    item = meta[key]
    artist = item.get("artist") or "автор не указан"
    license_name = item.get("license") or "лицензия см. на странице файла"
    return f"Фото: {artist}. {license_name}. Wikimedia Commons, файл «{item['file']}»."


def family_html(fam, meta):
    img = (PHOTO / f"{fam['photo']}.jpg").resolve().as_uri()
    paras = "".join(f"<p>{esc(p)}</p>" for p in fam["intro"])
    plates = []
    for name, fit in fam["plates"]:
        src = (HERE / "plates" / name).resolve().as_uri()
        klass = "plate fit" if fit else "plate"
        plates.append(
            f'<figure class="{klass}"><img src="{src}" alt="{esc(fam["title"])}"></figure>'
        )
    return f"""
    <section class="family" id="{fam['id']}">
      <h2>{esc(fam['title'])}</h2>
      {paras}
      <figure class="shot">
        <img src="{img}" alt="{esc(fam['title'])}">
        <figcaption>{esc(credit(meta, fam['photo']))}</figcaption>
      </figure>
      {''.join(plates)}
      <p class="platecap">{esc(fam['plate_note'])}</p>
      {table(fam['rows'])}
      <p class="note">{esc(fam['notes'])}</p>
    </section>
    """


def toc():
    items = ['<li><a href="#boeing">Boeing</a></li>']
    for fam in FAMILIES:
        items.append(f'<li class="sub"><a href="#{fam["id"]}">{esc(fam["h"])}</a></li>')
    return "<ul class=\"toc\">" + "".join(items) + "</ul>"


